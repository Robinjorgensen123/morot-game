package gamelogic.Enemies;

public abstract class enemy {
        protected int enemySpeed;
        protected int enemyHealth;
        protected int enemyDamage;
        protected String enemyName;
        protected String enemyImage;

        public abstract void enemySpeed();
        public abstract void enemyHealth();
        public abstract void enemyDamage();
        public abstract void enemyName();
        public abstract void enemyImage();

     

}
